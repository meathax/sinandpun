#!/usr/bin/env python3
"""Regenerates runtime/src/ui_font_data.cpp from a TTF.

Default input is Dear ImGui's bundled Roboto-Medium.ttf (Apache-2.0, Christian Robertson / Google), which the
CMake fetch already places under build/native/_deps/imgui-src/misc/fonts. The font is only used by the in-game
options menu (runtime/src/game_ui.cpp). Nothing is downloaded.

    python tools/gen_ui_font.py [path/to/font.ttf]
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else \
    root / "build/native/_deps/imgui-src/misc/fonts/Roboto-Medium.ttf"
data = src.read_bytes()
lines = []
for i in range(0, len(data), 24):
    lines.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
out = root / "runtime/src/ui_font_data.cpp"
out.write_text(
    "// Generated by tools/gen_ui_font.py from " + src.name + " - do not edit.\n"
    "// Roboto Medium, Copyright 2011 Google Inc., licensed under the Apache License 2.0\n"
    "// (https://www.apache.org/licenses/LICENSE-2.0). Used for the in-game options menu only.\n"
    "#include \"game_ui_font.h\"\n\n"
    "namespace game_ui {\n"
    "const unsigned char kUiFontTtf[] = {\n" + "\n".join(lines) + "\n};\n"
    f"const unsigned int kUiFontTtfSize = {len(data)};\n"
    "} // namespace game_ui\n",
    encoding="utf-8", newline="\n")
print(f"wrote {out} ({len(data)} bytes of font)")
