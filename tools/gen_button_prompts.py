"""Generate original UI glyphs, not modified game artwork. Requires Pillow.

Uses the same Apache-2.0 Roboto Medium font as the options menu. No game data
is read or embedded. Indices 0..14 follow SDL gamepad buttons; 15/16 are
triggers, 17/18 sticks, 19 d-pad, 20 unbound, 21 touchpad, 22 auxiliary.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / 'build/native/_deps/imgui-src/misc/fonts/Roboto-Medium.ttf'
S = 4
_HD = False  # set by --hd: draw at 16x and keep 128 px (4x) glyphs for the high-resolution atlas
WHITE = (237, 240, 245, 255)
COLORS = [(108, 207, 117, 255), (247, 107, 111, 255),
          (106, 177, 246, 255), (248, 207, 92, 255)]


def glyph(ps, index):
    im = Image.new('RGBA', (32*S, 32*S))
    d = ImageDraw.Draw(im)
    def line(points, color=WHITE, width=2):
        d.line([(x*S, y*S) for x, y in points], fill=color, width=width*S, joint='curve')
    def text(label, size=16):
        f = ImageFont.truetype(str(FONT), size*S)
        d.text((16*S, 16*S), label, font=f, anchor='mm', fill=WHITE, stroke_width=0)
    fill = (28, 32, 40, 255)
    d.ellipse((2*S, 2*S, 30*S, 30*S), fill=fill, outline=(160, 170, 187, 255), width=S)
    if index < 4:
        if ps:
            c = [(145,184,255,255),(255,134,143,255),(236,159,211,255),(122,223,187,255)][index]
            if index == 0:
                line([(10,10),(22,22)],c);line([(22,10),(10,22)],c)
            elif index == 1:d.ellipse((9*S,9*S,23*S,23*S),outline=c,width=2*S)
            elif index == 2:line([(10,10),(22,10),(22,22),(10,22),(10,10)],c)
            else:line([(16,8),(24,22),(8,22),(16,8)],c)
        else:
            f = ImageFont.truetype(str(FONT), 22*S)
            d.text((16*S,16*S),'ABXY'[index],font=f,anchor='mm',fill=COLORS[index])
    elif index in (9,10,15,16):
        im = Image.new('RGBA',im.size);d=ImageDraw.Draw(im)
        d.rounded_rectangle((S,6*S,31*S,26*S),radius=5*S,fill=fill,outline=WHITE,width=S)
        text(({9:'L1',10:'R1',15:'L2',16:'R2'} if ps else
              {9:'LB',10:'RB',15:'LT',16:'RT'})[index],16)
    elif index == 6:
        for y in (11,16,21):line([(10,y),(22,y)])
    elif index == 4:
        if ps:text('SH',13)
        else:
            line([(9,11),(19,11),(19,19),(9,19),(9,11)],width=1)
            line([(13,14),(23,14),(23,22),(13,22),(13,14)],width=1)
    elif index == 5:text('PS' if ps else 'X',16)
    elif index in (7,8,17,18):
        text(('L3' if index==7 else 'R3') if ps and index in (7,8) else
             ('L' if index in (7,17) else 'R'),16)
        if index in (7,8):line([(13,25),(16,28),(19,25)],width=1)
    elif index in (11,12,13,14):
        pts=[(16,8),(9,18),(13,18),(13,24),(19,24),(19,18),(23,18)]
        angle={11:0,12:180,13:90,14:270}[index]
        arrow=Image.new('RGBA',im.size);ad=ImageDraw.Draw(arrow)
        ad.polygon([(x*S,y*S) for x,y in pts],fill=WHITE)
        im.alpha_composite(arrow.rotate(angle))
    elif index==19:
        line([(16,8),(16,24)],width=5);line([(8,16),(24,16)],width=5)
    elif index==20:text('-',20)
    elif index==21:text('TP',13)
    else:text('M',16)
    return im.resize((32,32),Image.Resampling.LANCZOS) if not _HD else im.resize((128,128),Image.Resampling.LANCZOS)


def main():
    data=[]
    preview=Image.new('RGB',(23*40,90),(58,62,70))
    for ps in (False,True):
        for index in range(23):
            im=glyph(ps,index);data.extend(im.tobytes())
            preview.paste(im,(index*40,5+int(ps)*45),im)
    target=ROOT/'runtime/include/button_prompt_pixels.h'
    lines=['// Generated by tools/gen_button_prompts.py. Original UI artwork; Roboto Apache-2.0.',
           '#pragma once','#include <cstdint>','namespace ButtonPrompts {',
           'inline constexpr uint8_t kGlyphPixels[2][23][32 * 32 * 4] = {']
    for style in range(2):
        lines.append('{')
        for icon in range(23):
            a=(style*23+icon)*4096
            lines.append('{')
            for n in range(a,a+4096,64):lines.append(','.join(str(v) for v in data[n:n+64])+',')
            lines.append('},')
        lines.append('},')
    lines.extend(['};','} // namespace ButtonPrompts',''])
    target.write_text('\n'.join(lines),encoding='utf-8')
    out=ROOT/'build/prompt-assets';out.mkdir(parents=True,exist_ok=True)
    preview.save(out/'modern-glyphs.png')
    print(f'Generated {len(data)} bytes of original RGBA glyphs')


def main_hd():
    """128 px glyphs, run-length encoded, for the 1024x1024 high-resolution prompt atlas."""
    global S, _HD
    S, _HD = 16, True
    blobs = []
    preview = Image.new('RGB', (23*136, 2*136), (58, 62, 70))
    for ps in (False, True):
        for index in range(23):
            im = glyph(ps, index)
            preview.paste(im, (index*136, int(ps)*136), im)
            px = im.tobytes(); runs = bytearray(); i = 0
            while i < len(px):
                cur = px[i:i+4]; n = 1
                while n < 255 and i + 4*n < len(px) and px[i+4*n:i+4*n+4] == cur: n += 1
                runs.append(n); runs.extend(cur); i += 4*n
            blobs.append(bytes(runs))
    offsets = [0]
    for b in blobs: offsets.append(offsets[-1] + len(b))
    data = b''.join(blobs)
    lines = ['// Generated by tools/gen_button_prompts.py --hd. Original UI artwork; Roboto Apache-2.0.',
             '// 128x128 RGBA glyphs, run-length encoded as (count, r, g, b, a) records.',
             '#pragma once', '#include <cstdint>', 'namespace ButtonPrompts {',
             'inline constexpr int kGlyphHdSize = 128;',
             f'inline constexpr uint32_t kGlyphHdOffsets[{len(offsets)}] = {{' + ','.join(map(str, offsets)) + '};',
             f'inline constexpr uint8_t kGlyphHdRuns[{len(data)}] = {{']
    for n in range(0, len(data), 96): lines.append(','.join(str(v) for v in data[n:n+96]) + ',')
    lines.extend(['};', '} // namespace ButtonPrompts', ''])
    (ROOT/'runtime/include/button_prompt_pixels_hd.h').write_text(chr(10).join(lines), encoding='utf-8')
    out = ROOT/'build/prompt-assets'; out.mkdir(parents=True, exist_ok=True); preview.save(out/'modern-glyphs-hd.png')
    print(f'Generated {len(data)} RLE bytes for {len(blobs)} 128 px glyphs')


if __name__=='__main__':
    import sys
    main_hd() if '--hd' in sys.argv else main()
